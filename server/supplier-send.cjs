'use strict';
const {createHash}=require('node:crypto');
// Framework-neutral endpoint. createUserClient must verify JWT through Supabase;
// the RPC independently enforces active Admin membership. No caller-supplied role.
function createQueueHandler({createUserClient}){
  return async function(request){
    if(request.method!=='POST')return Response.json({error:'METHOD'},{status:405});
    try{
      const token=/^Bearer (\S+)$/.exec(request.headers.get('authorization')||'')?.[1];
      if(!token)return Response.json({error:'AUTH_REQUIRED'},{status:401});
      const client=await createUserClient(token),user=await client.auth.getUser(token);
      if(user.error||!user.data?.user?.id)return Response.json({error:'AUTH_REQUIRED'},{status:401});
      const raw=await request.text();if(Buffer.byteLength(raw)>4096)return Response.json({error:'SIZE'},{status:413});
      const b=JSON.parse(raw),uuid=/^[0-9a-f]{8}-[0-9a-f]{4}-[1-8][0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}$/i;
      if(![b.organizationId,b.orderId,b.documentId,b.requestId].every(x=>typeof x==='string'&&uuid.test(x))||!Number.isInteger(b.revision)||b.revision<1||typeof b.recipient!=='string'||b.recipient.length>254)
        return Response.json({error:'INPUT'},{status:400});
      const {data,error}=await client.schema('mir_core').rpc('queue_supplier_pdf',{org:b.organizationId,po:b.orderId,expected_revision:b.revision,document:b.documentId,request_id:b.requestId,confirmed_recipient:b.recipient});
      if(error)return Response.json({error:error.code==='42501'?'ADMIN_REQUIRED':'QUEUE_REJECTED'},{status:error.code==='42501'?403:409});
      if(typeof data!=='string'||!uuid.test(data))throw Error('Queue confirmation missing');
      return Response.json({ok:true,state:'queued',jobId:data},{status:202});
    }catch{return Response.json({error:'REQUEST_FAILED'},{status:400});}
  };
}
// No default provider: unconfigured services fail closed, never report sent.
// repository.claim/finish use a durable lease (see postgres-send-repository.cjs).
async function processNext({repository,storage,provider,sender}){
  if(!provider||provider.supportsIdempotency!==true||sender?.verified!==true||!sender.address)throw Error('Expéditeur vérifié et prestataire idempotent requis');
  const job=await repository.claim();if(!job)return {state:'idle'};
  try{
    // Every retry uses the same UUID at the email provider, including after an
    // uncertain network result. No new send key is generated by a retry.
    const pdf=await storage.read(job.object_path);
    if(!Buffer.isBuffer(pdf)||pdf.subarray(0,5).toString()!=='%PDF-'||createHash('sha256').update(pdf).digest('hex')!==job.sha256)throw Error('PDF privé invalide ou empreinte incorrecte');
    const receipt=await provider.send({idempotencyKey:job.id,from:sender.address,to:job.recipient,
      subject:'Bon de commande MIR — révision '+job.revision,
      text:'Veuillez trouver le bon de commande MIR en pièce jointe.',
      attachments:[{filename:'MIR-BC-'+job.order_id+'-R'+job.revision+'.pdf',contentType:'application/pdf',content:pdf}]});
    if(typeof receipt?.messageId!=='string'||!receipt.messageId.trim()||receipt.accepted!==true)throw Error('Confirmation prestataire absente');
    const recorded=await repository.finish(job,{status:'accepted',messageId:receipt.messageId});
    return {state:recorded?'accepted':'uncertain',jobId:job.id};
  }catch(error){
    // Conservative: without durable proof of rejection, do not resend blindly.
    await repository.finish(job,{status:'uncertain',error:'Transmission non confirmée : rapprochement requis'});
    return {state:'uncertain',jobId:job.id};
  }
}
async function retryUncertain({repository,provider,jobId}){
  if(provider?.supportsIdempotency!==true||typeof provider.lookup!=='function')throw Error('Rapprochement prestataire requis');
  const receipt=await provider.lookup(jobId);
  if(receipt?.accepted===true&&typeof receipt.messageId==='string'&&receipt.messageId.trim())return repository.resolveUncertain(jobId,receipt.messageId);
  // A timeout or an eventually-consistent "not found" is NOT proof of rejection.
  if(receipt?.definitivelyNotAccepted===true)return repository.requeue(jobId);
  return {state:'uncertain'};
}
module.exports={createQueueHandler,processNext,retryUncertain};
