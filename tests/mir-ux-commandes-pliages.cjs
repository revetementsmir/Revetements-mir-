'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),vm=require('node:vm');
const source=fs.readFileSync('dist/mir-unified-order-cart.js','utf8'),values=new Map(),events=[];
const window={crypto:{randomUUID:()=>`id-${values.size+1}`},dispatchEvent:event=>events.push(event)};
const context={window,localStorage:{getItem:key=>values.get(key)||null,setItem:(key,value)=>values.set(key,value)},CustomEvent:class{constructor(type,options){this.type=type;this.detail=options?.detail;}}};
vm.runInNewContext(source,context);
const cart=window.MIRUnifiedOrderCart;
assert.throws(()=>cart.upsert({kind:'material',quantity:0}),/quantité entière/);
assert.throws(()=>cart.upsert({kind:'fold',quantity:1.5}),/quantité entière/);
const material=cart.upsert({id:'material-1',kind:'material',quantity:2,line:{name:'Vis'}});
const fold=cart.upsert({id:'fold-1',kind:'fold',quantity:3,line:{name:'Solin',specification:{snapshot:'immutable'}}});
assert.deepEqual({...cart.counts()},{materials:1,folds:1});
assert.equal(cart.list()[1].line.specification.snapshot,'immutable');
cart.upsert({...material,quantity:4});
assert.equal(cart.list().find(line=>line.id==='material-1').quantity,4);
assert.ok(cart.duplicate(fold.id));assert.equal(cart.counts().folds,2);
cart.remove('material-1');assert.deepEqual({...cart.counts()},{materials:0,folds:2});
cart.clear();assert.equal(cart.list().length,0);assert.ok(events.length>=6);

const app=fs.readFileSync('dist/chantier-app.js','utf8'),production=fs.readFileSync('dist/production-app.js','utf8'),sql=fs.readFileSync('supabase/migrations/20261125120000_phase6_commandes_ux_pliages.sql','utf8');
assert.match(app,/production\.html\?mode=client&source=store&kind=profile/);
assert.match(app,/value="" placeholder="Quantité" required/);
assert.match(app,/Chantier à confirmer/);
assert.match(app,/maximum 6/);
assert.match(production,/MIRUnifiedOrderCart\?\.upsert/);
assert.match(production,/Indiquez une quantité entière supérieure à zéro/);
for(const required of ['enable row level security','user_id=auth.uid()','Maximum de six favoris atteint','pending_job_match_status','grant execute'])assert.match(sql,new RegExp(required.replace(/[.*+?^${}()|[\]\\]/g,'\\$&'),'i'));
assert.doesNotMatch(sql,/service_role|supabase\.co|gccltmaulvrnthrbnrpd|hxtztkmbfpmzrieccwsg/);
console.log('UX Commandes + Pliages: panier, quantité, favoris, chantier et sécurité OK');
