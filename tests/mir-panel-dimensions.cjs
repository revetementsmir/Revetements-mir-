'use strict';
const assert=require('node:assert/strict');
const M=require('../dist/production-model.js');
const E=require('../dist/panel-layout-engine.js');
const D=require('../dist/mir-panel-dimensions.js');
const approx=(a,b,epsilon=1e-8)=>assert.ok(Math.abs(a-b)<epsilon,`${a} !== ${b}`);
const base=E.build({widthIn:120,heightIn:96,lipIn:1,columns:4,rows:2,mode:'equal',precisionIn:0});
assert.equal(base.ok,true,JSON.stringify(base.errors));
assert.equal(base.pieces.length,8);
const first=base.pieces[0];
assert.equal(D.inputInches('25.4','mm',M),1);
approx(D.inputInches('31 1/2','in',M),31.5);
assert.equal(D.display(12.5,'mm'),'317.5');
assert.match(D.both(10,n=>n+' po'),/254 mm/);
const width=first.widthIn+1,height=first.heightIn+.5;
const applied=D.setPiece(base,first,width,height,E,{lock:true});
assert.equal(applied.ok,true,JSON.stringify(applied.errors));
approx(applied.columnWidthsIn[first.col],width);approx(applied.rowHeightsIn[first.row],height);
assert.equal(applied.config.widthLocks[first.col],width);
assert.equal(applied.config.heightLocks[first.row],height);
approx(applied.checks.assembledWidthIn,120);approx(applied.checks.assembledHeightIn,96);
for(const piece of applied.pieces){
 if(piece.col===first.col)approx(piece.widthIn,width);
 if(piece.row===first.row)approx(piece.heightIn,height);
}
assert.equal(base.config.widthLocks?.[first.col],undefined,'Original config remains unchanged');
assert.equal(base.config.heightLocks?.[first.row],undefined,'Original config remains unchanged');
const failed=D.setPiece(base,first,width,10000,E,{lock:true});
assert.equal(failed.ok,false);
assert.equal(base.config.widthLocks?.[first.col],undefined,'Atomic failure leaves original state unchanged');
const impossible=D.setPiece(base,first,5000,12,E);
assert.equal(impossible.ok,false);
assert.equal(D.inputInches('-2','in',M),null);
assert.equal(D.inputInches('not-a-number','mm',M),null);
console.log('PASS MIR per-panel inch/mm conversion, aligned grid locks, closure and atomic failure');
