'use strict';
const assert=require('node:assert/strict'),vm=require('node:vm'),fs=require('node:fs'),path=require('node:path');
const D=path.resolve(__dirname,'../dist'),sandbox={window:{}};
vm.runInNewContext(fs.readFileSync(path.join(D,'plan-3d.js'),'utf8'),sandbox);
const E=sandbox.window.MIR3D;
const site=E.commercialSitePlan(E.defaults,{siteStyle:'commercial'});
assert.ok(site&&site.parkingBayCount>=3&&site.surfaces.some(p=>p.id==='entree-asphalte'));
assert.ok(site.surfaces.some(p=>p.id==='trottoir')&&site.surfaces.some(p=>p.id==='stationnement-asphalte'));
assert.equal(site.noVehicles,true);
assert.equal(E.commercialSitePlan(E.defaults,{siteStyle:'none'}),null);
const study=E.studyDefaults();
const mesh=E.mesh({...study,dimensions:E.defaults,concreteSteps:{enabled:true,count:5}});
assert.equal(mesh.faces.filter(f=>f.role==='concrete-step'&&f.id.endsWith('-top')).length,5);
assert.ok(mesh.faces.every(f=>f.role!=='concrete-step'||f.notCertifiedTakeoff));
const notes=require('../dist/plan-structure-notes.js');
const hints=notes.detect([{text:'MARCHES DE BÉTON',box:[2,4,140,23],source:'pdf-text'}]);
assert.equal(hints[0].type,'stairs');assert.equal(hints[0].concreteMaterialHint,true);
assert.equal(hints[0].needsReview,true);
assert.equal(notes.detect([{text:'escalier',box:[2,4,140,23]}])[0].concreteMaterialHint,false);
assert.equal(notes.detect([{text:'poutre',box:[2,4,140,23]}])[0].type,'beam');
console.log('MIR terrain, marches béton et repères PDF : 12 contrôles vérifiés');