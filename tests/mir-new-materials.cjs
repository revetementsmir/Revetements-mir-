'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path');
const base=path.resolve(__dirname,'../dist'),src=n=>fs.readFileSync(path.join(base,n),'utf8');
const c=JSON.parse(src('catalogue-fd6866b49d21.json')).materials;
const byId=id=>{const m=c.find(x=>x.id===id);assert.ok(m,'Produit absent : '+id);return m;};
const can=byId('canexel-vstyle'),st=byId('st-laurent-v-groove-825'),bb=byId('hardie-board-batten');
assert.equal(can.verticalLayout.maxRunIn,144);
assert.equal(st.verticalLayout.maxRunIn,144);
assert.equal(can.allowedOrientations[0],'vertical');
assert.equal(st.allowedOrientations[0],'vertical');
assert.equal(bb.verticalLayout.maxRunIn,120);
assert.deepEqual(bb.verticalLayout.battenSpacingOptionsIn,[8,12,16]);
assert.ok(bb.documents.some(d=>d.url.includes('hardie-trim-batten-boards')));
assert.ok(bb.formats.some(f=>f.id==='48x96')&&bb.formats.some(f=>f.id==='48x120'));
const profilec=c.filter(m=>m.brand==='Profilec');
assert.ok(profilec.length>=10);
assert.deepEqual(new Set(profilec.map(m=>m.id)).size,profilec.length);
for(const m of profilec){
 assert.ok(m.sourceUrl.startsWith('https://www.profilec.ca/'));
 assert.ok(m.documents.some(d=>d.url.startsWith('https://www.profilec.ca/')));
 assert.notEqual(m.commercialStatus,'orderable');
 assert.ok(m.colors.every(color=>color.hex===null||/^#[0-9a-fA-F]{6}$/.test(color.hex)));
}
assert.ok(byId('profilec-la-muralys').applications.includes('siding'));
assert.ok(byId('profilec-la-capitale').applications.includes('roofing'));
assert.ok(byId('profilec-lancestra').applications.includes('roofing'));
const beck=byId('beck-panelfast-ags100');
assert.equal(beck.brand,'BECK Fastener Group');
assert.deepEqual(beck.formats.map(format=>format.manufacturerCode),['AGS1000150-NA']);
assert.deepEqual(beck.formats.map(format=>format.lengthIn),[1.5]);
assert.equal(beck.packaging.piecesPerCoil,250);
assert.equal(beck.packaging.coilsPerBox,12);
assert.equal(beck.packaging.piecesPerBox,3000);
assert.equal(beck.images.length,2);
assert.ok(beck.images.every(image=>fs.existsSync(path.resolve(base,image.src.replace(/^\.\//,'')))));
assert.ok(beck.documents.some(document=>document.verified&&document.url.includes('beck-fastening.com')));
assert.equal(beck.mirFixedPriceCents,51599);
assert.equal(beck.unit,'boîte de 12 bobines (3 000 clous)');
const masonry=c.filter(m=>m.applications.includes('masonry'));
const surface=require('../dist/material-surface.js'),coverage=require('../dist/material-coverage.js');
assert.equal(masonry.filter(m=>m.name.startsWith('Brique')).length,3);
assert.equal(masonry.filter(m=>m.name.startsWith('Pierre')).length,3);
const layouts=new Set();
for(const material of masonry){
 assert.equal(material.status,'visualization_only');
 assert.equal(material.commercialStatus,'not_for_sale');
 assert.equal(material.colors.length,0);
 assert.ok(material.previewColors.length>=5);
 assert.equal(new Set(material.previewColors.map(c=>c.id)).size,material.previewColors.length);
 assert.equal(new Set(material.previewColors.map(c=>c.hex)).size,material.previewColors.length);
 assert.ok(material.previewColors.every(c=>/^#[0-9a-f]{6}$/i.test(c.hex)));
 assert.equal(coverage.coverageSpec(material).complete,false);
 const pattern=color=>surface.patternDef({id:'preview',material,choice:{color},feetPerPixel:.031,anchorY:13});
 const drawing=pattern('#98644e');
 assert.match(drawing,/data-scale-status="illustrative"/);
 assert.notEqual(drawing,pattern('#8b8c84'));
 layouts.add([...drawing.matchAll(/<polygon points="([^"]+)"/g)].map(m=>m[1]).join(' '));
}
assert.ok([...layouts].every(Boolean));
assert.equal(layouts.size,masonry.length,'Chaque profil possède son propre dessin de joints');
const app=src('plan-app.js'),html=src('plan.html');
assert.ok(app.includes('V.breaks(')&&app.includes('V.battens('));
assert.ok(app.includes('data-mir-auto-transition')&&app.includes('data-mir-batten-spacing'));
assert.ok(html.includes('id="batten-spacing"')&&html.includes('mir-vertical-layout.js'));
console.log('MIR nouvelles matières : '+c.length+' fiches, '+profilec.length+' Profilec, 3 produits verticaux et '+masonry.length+' styles de maçonnerie illustratifs');
